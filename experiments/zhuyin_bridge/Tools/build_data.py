#!/usr/bin/env python3
"""Generate finite syllable data and identical Swift / browser resources.

This is an explicitly bounded teaching lexicon, not a production dictionary.
No third-party dictionary is redistributed. Run from any directory.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
INITIALS = dict(zip('b p m f d t n l g k h j q x zh ch sh r z c s'.split(), 'ㄅㄆㄇㄈㄉㄊㄋㄌㄍㄎㄏㄐㄑㄒㄓㄔㄕㄖㄗㄘㄙ'))
FINALS = dict(zip(
    'a o e ê ai ei ao ou an en ang eng er i ia io ie iao iu ian in iang ing u ua uo uai ui uan un uang ong ü üe üan ün iong'.split(),
    'ㄚ ㄛ ㄜ ㄝ ㄞ ㄟ ㄠ ㄡ ㄢ ㄣ ㄤ ㄥ ㄦ ㄧ ㄧㄚ ㄧㄛ ㄧㄝ ㄧㄠ ㄧㄡ ㄧㄢ ㄧㄣ ㄧㄤ ㄧㄥ ㄨ ㄨㄚ ㄨㄛ ㄨㄞ ㄨㄟ ㄨㄢ ㄨㄣ ㄨㄤ ㄨㄥ ㄩ ㄩㄝ ㄩㄢ ㄩㄣ ㄩㄥ'.split()
))
# Deliberately finite common-Mandarin inventory. Excludes syllabic m/n/ng,
# dialect readings and productive erhua. Not a claim of full Mandarin coverage.
INVENTORY = {
    'b': 'a o ai ei ao an en ang eng i ie iao ian in ing u',
    'p': 'a o ai ei ao ou an en ang eng i ie iao ian in ing u',
    'm': 'a o e ai ei ao ou an en ang eng i ie iao iu ian in ing u',
    'f': 'a o ei ou an en ang eng u',
    'd': 'a e ai ei ao ou an en ang eng i ie iao iu ian ing u uo ui uan un ong',
    't': 'a e ai ao ou an ang eng i ie iao ian ing u uo ui uan un ong',
    'n': 'a e ai ei ao ou an en ang eng i ie iao iu ian in iang ing u uo uan ong ü üe',
    'l': 'a o e ai ei ao ou an ang eng i ia ie iao iu ian in iang ing u uo uan un ong ü üe',
    'g': 'a e ai ei ao ou an en ang eng u ua uo uai ui uan un uang ong',
    'k': 'a e ai ei ao ou an en ang eng u ua uo uai ui uan un uang ong',
    'h': 'a e ai ei ao ou an en ang eng u ua uo uai ui uan un uang ong',
    'j': 'i ia ie iao iu ian in iang ing u ue uan un iong',
    'q': 'i ia ie iao iu ian in iang ing u ue uan un iong',
    'x': 'i ia ie iao iu ian in iang ing u ue uan un iong',
    'zh': 'i a e ai ei ao ou an en ang eng u ua uo uai ui uan un uang ong',
    'ch': 'i a e ai ao ou an en ang eng u ua uo uai ui uan un uang ong',
    'sh': 'i a e ai ei ao ou an en ang eng u ua uo uai ui uan un uang',
    'r': 'i e ao ou an en ang eng u uo ui uan un ong',
    'z': 'i a e ai ei ao ou an en ang eng u uo ui uan un ong',
    'c': 'i a e ai ao ou an en ang eng u uo ui uan un ong',
    's': 'i a e ai ao ou an en ang eng u uo ui uan un ong',
}
ZERO = dict(zip(
    'a o e ê ai ei ao ou an en ang eng er yi ya yo ye yao you yan yin yang ying wu wa wo wai wei wan wen wang weng yu yue yuan yun yong'.split(),
    'ㄚ ㄛ ㄜ ㄝ ㄞ ㄟ ㄠ ㄡ ㄢ ㄣ ㄤ ㄥ ㄦ ㄧ ㄧㄚ ㄧㄛ ㄧㄝ ㄧㄠ ㄧㄡ ㄧㄢ ㄧㄣ ㄧㄤ ㄧㄥ ㄨ ㄨㄚ ㄨㄛ ㄨㄞ ㄨㄟ ㄨㄢ ㄨㄣ ㄨㄤ ㄨㄥ ㄩ ㄩㄝ ㄩㄢ ㄩㄣ ㄩㄥ'.split()
))

def build():
    syllables = dict(ZERO)
    for initial, finals in INVENTORY.items():
        for final in finals.split():
            written = final
            if initial in ('j', 'q', 'x') and final.startswith('u'):
                written = 'ü' + final[1:]
            if initial in ('zh', 'ch', 'sh', 'r', 'z', 'c', 's') and final == 'i':
                syllables[initial + final] = INITIALS[initial]
            else:
                syllables[initial + final] = INITIALS[initial] + FINALS[written]
    assert len(set(syllables.values())) == len(syllables), 'ambiguous canonical readings'
    hints = list(INITIALS) + 'i u ü a o e ê ai ei ao ou an en ang eng er'.split()
    symbols = list('ㄅㄆㄇㄈㄉㄊㄋㄌㄍㄎㄏㄐㄑㄒㄓㄔㄕㄖㄗㄘㄙㄧㄨㄩㄚㄛㄜㄝㄞㄟㄠㄡㄢㄣㄤㄥㄦ')
    keys = [dict(symbol=s, hint=h) for s, h in zip(symbols, hints)]
    rows = [keys[:10], keys[10:20], keys[20:30], keys[30:]]
    lexicon = []
    for line in (ROOT / 'Data/lexicon.tsv').read_text().splitlines():
        if not line or line.startswith('#'):
            continue
        reading, traditional, simplified = line.split('\t')
        pinyin = reading.split()
        for p in pinyin:
            assert p[-1] in '12345' and p[:-1] in syllables, p
        lexicon.append(dict(readings=pinyin, traditional=traditional, simplified=simplified))
    data = dict(version=1, syllables=[dict(pinyin=p, zhuyin=z) for p, z in sorted(syllables.items())], rows=rows, lexicon=lexicon)
    raw = json.dumps(data, ensure_ascii=False, separators=(',', ':'))
    (ROOT / 'Data/bridge.json').write_text(json.dumps(data, ensure_ascii=False, indent=2) + '\n')
    (ROOT / 'Web/data.js').write_text('globalThis.BRIDGE_DATA = ' + raw + ';\n')
    (ROOT / 'Shared/BridgeData.swift').write_text('''// Generated by Tools/build_data.py; do not edit.
import Foundation

enum BridgeData {
    static let value: BridgeDataset = {
        let json = #"""
''' + raw + '''
"""#
        // A corrupt bundled resource is a build defect; verified by data tests.
        return try! JSONDecoder().decode(BridgeDataset.self, from: Data(json.utf8))
    }()
}
''')
    print(f'Generated {len(syllables)} syllable spellings, {len(keys)} keys, {len(lexicon)} teaching entries.')

if __name__ == '__main__':
    build()
